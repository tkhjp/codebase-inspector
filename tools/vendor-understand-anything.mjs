#!/usr/bin/env node

import { execFile } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { isAbsolute, join } from "node:path";
import { fileURLToPath, URL } from "node:url";
import { promisify } from "node:util";

const PINNED_COMMIT = "54754a6f97051d1d76c8758353d8ea41afe502a6";
const EXTRACTORS = ["typescript", "python", "rust", "go", "java", "kotlin", "csharp", "cpp", "php", "ruby", "dart"];
const SOURCE_ROOT = "understand-anything-plugin/packages/core/src/plugins/extractors";
const VENDOR_ROOT = ".github/skills/codebase-inspector/vendor/understand-anything";
const execFileAsync = promisify(execFile);
const repositoryRoot = fileURLToPath(new URL("..", import.meta.url));
const require = createRequire(new URL("../.github/skills/codebase-inspector/package.json", import.meta.url));
const { transform } = require("esbuild");

function usage() {
  return "Usage: node tools/vendor-understand-anything.mjs --upstream /absolute/path/Understand-Anything";
}

function parseArguments(argv) {
  if (argv.length !== 2 || argv[0] !== "--upstream" || !argv[1]) {
    throw new Error(usage());
  }
  if (!isAbsolute(argv[1])) throw new Error(`Upstream path must be absolute.\n${usage()}`);
  return argv[1];
}

async function git(upstream, ...args) {
  const { stdout } = await execFileAsync("git", ["-C", upstream, ...args], { encoding: "utf8" });
  return stdout.trim();
}

function normalizeLf(value) {
  return value.replace(/\r\n?/g, "\n");
}

function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

function sortedKeys(value) {
  if (Array.isArray(value)) return value.map(sortedKeys);
  if (!value || typeof value !== "object") return value;
  return Object.fromEntries(Object.keys(value).sort().map((key) => [key, sortedKeys(value[key])]));
}

function sourcePathFor(sourceName) {
  return join(SOURCE_ROOT, sourceName).replaceAll("\\", "/");
}

function provenanceHeader(sourceName) {
  return [
    "// SPDX-License-Identifier: MIT",
    "// Vendored from Egonex-AI/Understand-Anything.",
    `// Source: ${sourcePathFor(sourceName)} @ ${PINNED_COMMIT}`,
    "// Generated by tools/vendor-understand-anything.mjs; do not edit.",
    ""
  ].join("\n");
}

async function generateModule(upstream, sourceName, generatedName) {
  const sourcePath = sourcePathFor(sourceName);
  const source = await readFile(join(upstream, sourcePath), "utf8");
  const transformed = await transform(source, { loader: "ts", format: "esm", target: "node22" });
  const rewritten = transformed.code.replace(/(["'])\.\/base-extractor\.js\1/g, "$1./base-extractor.mjs$1");
  const generated = normalizeLf(`${provenanceHeader(sourceName)}${rewritten}`);
  const generatedPath = join(VENDOR_ROOT, "extractors", generatedName);

  await writeFile(join(repositoryRoot, generatedPath), generated, "utf8");
  return {
    generatedPath: generatedPath.replaceAll("\\", "/"),
    generatedSha256: sha256(generated),
    sourcePath,
    sourceSha256: sha256(source)
  };
}

async function main() {
  const upstream = parseArguments(process.argv.slice(2));
  const head = await git(upstream, "rev-parse", "HEAD");
  if (head !== PINNED_COMMIT) {
    throw new Error(`Upstream HEAD must be ${PINNED_COMMIT}; received ${head}`);
  }
  if (await git(upstream, "status", "--porcelain")) {
    throw new Error("Upstream worktree must be clean");
  }

  await mkdir(join(repositoryRoot, VENDOR_ROOT, "extractors"), { recursive: true });
  const base = await generateModule(upstream, "base-extractor.ts", "base-extractor.mjs");
  const extractors = [];
  for (const name of EXTRACTORS) {
    extractors.push({ name, ...await generateModule(upstream, `${name}-extractor.ts`, `${name}-extractor.mjs`) });
  }
  extractors.sort((left, right) => left.name.localeCompare(right.name));

  const manifest = sortedKeys({
    base,
    extractors,
    localPatches: [],
    upstream: {
      commit: PINNED_COMMIT,
      license: "MIT",
      repository: "https://github.com/Egonex-AI/Understand-Anything"
    }
  });
  await writeFile(
    join(repositoryRoot, VENDOR_ROOT, "manifest.json"),
    `${JSON.stringify(manifest, null, 2)}\n`,
    "utf8"
  );
}

main().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});
